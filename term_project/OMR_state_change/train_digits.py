"""Train and export an ARM integer CNN from UCI Optical Recognition of Handwritten Digits.

Dataset by E. Alpaydin and C. Kaynak, CC BY 4.0, doi:10.24432/C50P49.
Dependencies: NumPy and Pillow. Input: extracted optdigits.tra and optdigits.tes.
"""
from argparse import ArgumentParser
from pathlib import Path

import numpy as np
from numpy.lib.stride_tricks import sliding_window_view
from PIL import Image


def load(path):
    data = np.loadtxt(path, delimiter=",", dtype=np.uint8)
    normalized = []
    for digit in data[:, :64].reshape(-1, 8, 8):
        y, x = np.where(digit >= 3)
        cropped = digit[y.min():y.max() + 1, x.min():x.max() + 1]
        image = Image.fromarray(cropped * 15)
        image = image.resize((8, 8), Image.Resampling.BILINEAR)
        normalized.append(np.rint(np.asarray(image, dtype=np.float32) / 15))
    return np.stack(normalized), data[:, -1]


def patches(images):
    return np.ascontiguousarray(
        sliding_window_view(images, (3, 3), axis=(1, 2)).reshape(-1, 36, 9)
    )


def features(blocks, kernel, bias):
    return np.maximum(blocks @ kernel + bias, 0).reshape(len(blocks), -1)


def train(images, labels):
    rng = np.random.default_rng(2022113913)
    blocks = patches(images / 16)
    kernel = rng.normal(0, 0.25, (9, 8)).astype(np.float32)
    bias = np.zeros(8, dtype=np.float32)
    dense = rng.normal(0, 0.08, (36 * 8, 10)).astype(np.float32)
    offset = np.zeros(10, dtype=np.float32)
    for epoch in range(42):
        order = rng.permutation(len(labels))
        rate = 0.08 if epoch < 26 else 0.035
        for start in range(0, len(order), 64):
            batch = order[start:start + 64]
            block = blocks[batch]
            encoded = features(block, kernel, bias)
            logits = encoded @ dense + offset
            probabilities = np.exp(logits - logits.max(axis=1, keepdims=True))
            probabilities /= probabilities.sum(axis=1, keepdims=True)
            probabilities[np.arange(len(batch)), labels[batch]] -= 1
            error = probabilities / len(batch)
            hidden = (error @ dense.T) * (encoded > 0)
            hidden = hidden.reshape(-1, 8)
            dense -= rate * (encoded.T @ error)
            offset -= rate * error.sum(axis=0)
            kernel -= rate * (block.reshape(-1, 9).T @ hidden)
            bias -= rate * hidden.sum(axis=0)
    return kernel, bias, dense, offset


def export(destination, arrays):
    types = ("int16_t", "int32_t", "int16_t", "int32_t")
    names = ("conv_weight", "conv_bias", "dense_weight", "dense_bias")
    with destination.open("w", encoding="ascii") as stream:
        stream.write("/* Generated by train_digits.py. Data: UCI optdigits, CC BY 4.0. */\n")
        stream.write("#ifndef OMR_DIGIT_MODEL_H\n#define OMR_DIGIT_MODEL_H\n\n#include <stdint.h>\n")
        for kind, name, array in zip(types, names, arrays):
            values = array.ravel()
            stream.write(f"\nstatic const {kind} {name}[{values.size}] = {{\n")
            for index in range(0, values.size, 16):
                stream.write("    " + ", ".join(map(str, values[index:index + 16])) + ",\n")
            stream.write("};\n")
        stream.write("\n#endif\n")


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("train", type=Path)
    parser.add_argument("test", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).parent /
                        "OMR_state_change.sdk/OMR_state_change_app/src/omr_digit_model.h")
    args = parser.parse_args()
    model = train(*load(args.train))
    scales = (64, 16 * 64, 128, 16 * 64 * 128)
    quantized = tuple(np.rint(value * scale).astype(np.int32)
                      for value, scale in zip(model, scales))
    test, labels = load(args.test)
    kernel, bias, dense, offset = quantized
    logits = features(patches(test.astype(np.int32)), kernel, bias) @ dense + offset
    correct = logits.argmax(axis=1) == labels
    ranks = np.sort(logits, axis=1)
    accepted = ranks[:, -1] - ranks[:, -2] >= 131072
    print(f"Test accuracy: {correct.mean():.3%}; "
          f"coverage: {accepted.mean():.3%}; accepted accuracy: {correct[accepted].mean():.3%}")
    export(args.output, quantized)


if __name__ == "__main__":
    main()
